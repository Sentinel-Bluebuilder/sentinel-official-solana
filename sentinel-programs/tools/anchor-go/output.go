package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

const generatedHeader = "// Code generated by tools/anchor-go with github.com/gagliardetto/anchor-go. DO NOT EDIT."

const upstreamHeader = "// Code generated by https://github.com/gagliardetto/anchor-go. DO NOT EDIT."

func finish(name string, src []byte) ([]byte, error) {
	out, err := applyRewrites(withHeader(src), fileRewrites...)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}

	return out, nil
}

func withHeader(src []byte) []byte {
	h := []byte(generatedHeader)

	if bytes.HasPrefix(src, []byte(upstreamHeader)) {
		return append(h, src[len(upstreamHeader):]...)
	}

	if bytes.HasPrefix(src, h) {
		return src
	}

	return append(append(h, '\n', '\n'), src...)
}

func write(out string, files map[string][]byte) error {
	parent := filepath.Dir(out)
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return err
	}

	tmp, err := os.MkdirTemp(parent, ".anchor-go-")
	if err != nil {
		return err
	}

	defer func() { _ = os.RemoveAll(tmp) }()

	for name, src := range files {
		if err := os.MkdirAll(filepath.Dir(filepath.Join(tmp, name)), 0o755); err != nil {
			return err
		}

		if err := os.WriteFile(filepath.Join(tmp, name), src, 0o644); err != nil {
			return err
		}
		if err := os.Chmod(filepath.Join(tmp, name), 0o644); err != nil {
			return err
		}
	}

	if err := os.Chmod(tmp, 0o755); err != nil {
		return err
	}

	old := ""
	if _, err := os.Lstat(out); err == nil {
		old, err = os.MkdirTemp(parent, ".anchor-go-old-")
		if err != nil {
			return err
		}

		if err := os.Remove(old); err != nil {
			return err
		}

		if err := os.Rename(out, old); err != nil {
			return err
		}
	} else if !os.IsNotExist(err) {
		return err
	}

	if err := os.Rename(tmp, out); err != nil {
		if old != "" {
			if restoreErr := os.Rename(old, out); restoreErr != nil {
				return fmt.Errorf("replace output: %w; rollback failed: %v; previous output retained at %s", err, restoreErr, old)
			}
		}

		return err
	}

	if old != "" {
		_ = os.RemoveAll(old)
	}

	return nil
}
